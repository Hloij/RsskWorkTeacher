        /// <summary>
        /// Безопасное извлечение числа из строки (например, "104" или "8 (подготовка 2)" или "-")
        /// </summary>
        private int ParseHours(string input)
        {
            if (string.IsNullOrWhiteSpace(input) || input.Trim() == "-") return 0;

            // Ищем первое вхождение цифр в строке
            var match = Regex.Match(input, @"\d+");
            if (match.Success && int.TryParse(match.Value, out int result))
            {
                return result;
            }
            return 0;
        }
    
